/**
 * API group ("vendor") -> icon path, for resources whose Kind isn't a built-in Kubernetes type but whose
 * apiVersion identifies a known CNCF (or other) vendor project — e.g. a `Certificate` (cert-manager.io/v1)
 * shows cert-manager's logo, a `CiliumNetworkPolicy` (cilium.io/v2) shows Cilium's. Sourced from the CNCF
 * artwork repo (github.com/cncf/artwork/tree/main/examples), the Simple Icons project
 * (github.com/simple-icons/simple-icons, CC0) for widely-used commercial products, gilbarbara/logos
 * (github.com/gilbarbara/logos, CC0) for a couple of brands Simple Icons doesn't carry, each project's own
 * repo for a couple of others (Gardener, Apache-2.0), plus a handful of vendors ported from the legacy app
 * (IBM, OpenShift, Kong, Rancher, Red Hat) that predate all of the above.
 *
 * `needle` is matched as a substring of the resource's apiVersion GROUP (the part before the "/", or the
 * whole string for a core-group-style apiVersion with no group) — never the full apiVersion including the
 * version suffix, so a coincidental match inside e.g. "v1beta1" can't happen. Ordered longest-needle-first so
 * a more specific group (e.g. "monitoring.coreos.com") is always tried before a shorter, broader one.
 *
 * `title` is display-only (the Settings > Vendor Icons review table) — never consulted by resolution.
 */
