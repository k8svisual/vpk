import { readdirSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, sep } from 'node:path';

/**
 * Regenerates packages/server/src/webAssets.generated.ts from packages/web/dist (a `vite build` output).
 *
 * Why codegen instead of a static import list: `bun build --compile` only embeds a file into a standalone
 * executable when it's reachable via a literal, statically-analyzable `import ... with { type: "file" }` —
 * Vite's build output has a different, hash-named set of files every build, so there's no fixed list to write
 * by hand. This script walks the actual dist/ output after a real `vite build` and writes ONE import per file
 * it finds, so `bun build --compile` on the server entrypoint (which imports the generated module) embeds the
 * whole built web app into the resulting binary — no separate assets folder to ship alongside it.
 *
 * The generated file is checked into the repo with EMPTY maps as a placeholder (see its own header comment) so
 * a normal `bun run dev:server` / `bun run typecheck` never depends on a web build existing. Running this
 * script overwrites it with the real embedded-asset list — that's expected to happen right before
 * `build:binary` in the release workflow (an ephemeral CI checkout, so nothing gets committed back); running
 * it locally will leave your working tree with a real (large, generated) diff in that one file — `git
 * checkout -- packages/server/src/webAssets.generated.ts` reverts it once you're done testing a local binary.
 */

const here = import.meta.dir;
const DIST_DIR = join(here, '../packages/web/dist');
const OUT_FILE = join(here, '../packages/server/src/webAssets.generated.ts');

function walk(dir: string, base: string): string[] {
  const out: string[] = [];
  for (const entry of readdirSync(dir)) {
    const full = join(dir, entry);
    if (statSync(full).isDirectory()) out.push(...walk(full, base));
    else out.push(relative(base, full));
  }
  return out;
}

function main() {
  if (!statSync(DIST_DIR, { throwIfNoEntry: false })?.isDirectory()) {
    console.error(`No build output at ${DIST_DIR} — run \`bun run build:web\` first.`);
    process.exit(1);
  }

  const files = walk(DIST_DIR, DIST_DIR).sort();
  if (files.length === 0) {
    console.error(`${DIST_DIR} is empty — \`bun run build:web\` didn't produce anything.`);
    process.exit(1);
  }

  const importLines: string[] = [];
  const mapEntries: string[] = [];
  files.forEach((relPath, i) => {
    const urlPath = '/' + relPath.split(sep).join('/');
    const varName = `f${i}`;
    importLines.push(`import ${varName} from '../../web/dist${urlPath}' with { type: 'file' };`);
    // Cast needed for .html specifically — bun-types' own ambient declaration types a `*.html` import as
    // HTMLBundle regardless of the `type: 'file'` attribute overriding that at runtime to a plain path
    // string (the same as every other extension here); the cast reflects actual runtime behavior, not a
    // workaround for wrong data.
    mapEntries.push(`  ${JSON.stringify(urlPath)}: ${varName} as unknown as string,`);
  });

  const contents = `// GENERATED by scripts/build-web-assets.ts — DO NOT EDIT BY HAND.
// See that script's header comment for why this exists and when it's regenerated.
${importLines.join('\n')}

/** URL path (as the browser will request it) -> embedded file path. Populated by build-web-assets.ts from a
 *  real \`vite build\` output; empty in a normal checkout, which is fine — server.ts's static handler simply
 *  has nothing to serve until this is regenerated ahead of a \`bun build --compile\`. */
export const WEB_ASSETS: Record<string, string> = {
${mapEntries.join('\n')}
};
`;

  writeFileSync(OUT_FILE, contents);
  console.log(`Wrote ${OUT_FILE} — embedded ${files.length} file(s) from ${DIST_DIR}.`);
}

main();
