import { readdirSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, sep } from 'node:path';

/**
 * Regenerates packages/server/src/courseAssets.generated.ts from the repo's courses/ directory — the seed
 * content a freshly-packaged binary extracts into a real writable directory on first run (see
 * course/seedCourses.ts).
 *
 * Same reasoning as build-web-assets.ts (see its own header comment): `bun build --compile` only embeds a file
 * into a standalone executable via a literal, statically-analyzable `import ... with { type: "file" }` — this
 * script walks courses/ and writes one such import per file it finds.
 *
 * The generated file is checked into the repo with an EMPTY map as a placeholder so a normal `bun run
 * dev:server` / `bun run typecheck` never depends on this having been run — dev reads courses/ straight off
 * disk (content.ts's DEFAULT_COURSES_DIR points at the real repo folder there). Running this script overwrites
 * it with the real embedded-asset list, expected right before `build:binary` in the release workflow; `git
 * checkout -- packages/server/src/courseAssets.generated.ts` reverts a local run once you're done testing.
 */

const here = import.meta.dir;
const COURSES_DIR = join(here, '../courses');
const OUT_FILE = join(here, '../packages/server/src/courseAssets.generated.ts');

function walk(dir: string, base: string): string[] {
  const out: string[] = [];
  for (const entry of readdirSync(dir)) {
    const full = join(dir, entry);
    if (statSync(full).isDirectory()) out.push(...walk(full, base));
    else out.push(relative(base, full));
  }
  return out;
}

function main() {
  if (!statSync(COURSES_DIR, { throwIfNoEntry: false })?.isDirectory()) {
    console.error(`No courses directory at ${COURSES_DIR}.`);
    process.exit(1);
  }

  const files = walk(COURSES_DIR, COURSES_DIR).sort();
  if (files.length === 0) {
    console.error(`${COURSES_DIR} is empty — nothing to embed.`);
    process.exit(1);
  }

  const importLines: string[] = [];
  const mapEntries: string[] = [];
  files.forEach((relPath, i) => {
    const coursePath = relPath.split(sep).join('/');
    const varName = `c${i}`;
    importLines.push(`import ${varName} from '../../courses/${coursePath}' with { type: 'file' };`);
    mapEntries.push(`  ${JSON.stringify(coursePath)}: ${varName} as unknown as string,`);
  });

  const contents = `// GENERATED by scripts/build-course-assets.ts — DO NOT EDIT BY HAND.
// See that script's header comment for why this exists and when it's regenerated.
${importLines.join('\n')}

/** Course-relative path (e.g. "course02/00-using-oc.md") -> embedded file path. Populated by
 *  build-course-assets.ts from the repo's real courses/ directory; empty in a normal checkout, which is fine —
 *  course/seedCourses.ts's extraction simply has nothing to seed until this is regenerated ahead of a
 *  \`bun build --compile\`. */
export const COURSE_ASSETS: Record<string, string> = {
${mapEntries.join('\n')}
};
`;

  writeFileSync(OUT_FILE, contents);
  console.log(`Wrote ${OUT_FILE} — embedded ${files.length} file(s) from ${COURSES_DIR}.`);
}

main();
